"""Network vehicles. All dimensions are before the game's existing 2x traffic scale."""

import math


def nozzle(m, x, y, z, r):
    n = 14 if m.detailed else 7
    m.barrel(
        (x, y, z - 0.67 * r),
        (x, y, z),
        [(0, r * 0.87), (0.62, r), (1, 0.94 * r)],
        ["hot", "alloy"],
        n,
        cap="graphite",
    )
    if not m.detailed:
        m.end(True, z + 0.01, x, y - 0.22 * r, r * 0.65, r * 0.44, "drive")
        return
    for j in range(n):
        a = math.tau * j / n
        b = math.tau * (j + 1) / n

        def point(ang, rad, depth):
            return (x + math.cos(ang) * rad, y + math.sin(ang) * rad, z + depth)

        m.face(
            [
                point(a, r * 0.92, 0.012),
                point(b, r * 0.92, 0.012),
                point(b, r * 0.7, 0.028),
                point(a, r * 0.7, 0.028),
            ],
            "hot" if j % 3 else "alloy",
        )
        m.face(
            [
                point(a, r * 0.70, 0.028),
                point(b, r * 0.70, 0.028),
                point(b, r * 0.46, 0.014),
                point(a, r * 0.46, 0.014),
            ],
            "vents",
        )
    m.barrel(
        (x, y, z + 0.018),
        (x, y, z + 0.032),
        [(0, r * 0.42), (1, r * 0.42)],
        "drive",
        10,
        cap="drive",
    )


def canopy(m, x, z, w, length, base, rise):
    sections = [
        (-0.50, 0.43, 0.05),
        (-0.29, 0.88, 0.78),
        (0.01, 1, 1),
        (0.29, 0.93, 0.96),
        (0.5, 0.65, 0.16),
    ]
    if not m.detailed:
        sections = sections[::2]
    m.hull(
        [
            (z + t * length, w * k, base - 0.07, base + rise * h, 0.76)
            for t, k, h in sections
        ],
        "glass",
        x,
        True,
    )
    if m.detailed:
        # Roof, sill gaskets and the paired diagonal window pillars carry the silhouette.
        m.hull(
            [
                (
                    z + t * length,
                    w * k,
                    base + rise * h - 0.065,
                    base + rise * h + 0.015,
                    0.92,
                )
                for t, k, h in [
                    (-0.27, 0.38, 0.79),
                    (0.02, 0.66, 1),
                    (0.27, 0.54, 0.97),
                ]
            ],
            "paint",
            x,
        )
        for side in (-1, 1):
            m.bar(
                (x + side * w * 0.46, base + 0.09, z + 0.15 * length),
                (x + side * w * 0.32, base + rise * 0.98, z + 0.08 * length),
                0.044 * max(w / 2, 1),
                "graphite",
                5,
            )
            m.bar(
                (x + side * w * 0.45, base + 0.1, z - 0.24 * length),
                (x + side * w * 0.28, base + rise * 0.77, z - 0.28 * length),
                0.032 * max(w / 2, 1),
                "alloy",
                5,
            )


